package io.tranzfa.core.auth.dto;

import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class PasskeyRegisterRequest {

    @Schema(description = "Unique credential identifier generated by the device Secure Enclave", example = "cred_ios_f81729")
    private String credentialId;

    @Schema(description = "Public key in Base64 / PEM / COSE format generated by the hardware authenticator")
    private String publicKey;

    @Schema(description = "Standard W3C WebAuthn attestation response JSON from navigator.credentials.create()")
    private String attestationResponseJson;

    @Schema(description = "Device UUID / fingerprint", example = "dev-ios-a918f-2831")
    private String deviceId;

    @Schema(description = "Device friendly name", example = "iPhone 15 Pro")
    private String deviceName;
}
